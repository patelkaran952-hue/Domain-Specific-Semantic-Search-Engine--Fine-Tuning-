"""Environment pinning and fresh-environment verification helpers (no network or heavy imports at import time)."""
from __future__ import annotations

import platform
import re
import sys
from importlib import metadata
from pathlib import Path

HEAVY = {"torch", "sentence-transformers", "transformers", "huggingface-hub", "huggingface_hub", "datasets", "accelerate"}
LITE_EXCLUDE = HEAVY | {"jupyter", "ipykernel", "nbconvert", "matplotlib"}
_NAME = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_requirements(path: Path) -> list[tuple[str, str]]:
    """[(normalized_name, original_line)] ignoring comments, blanks and options."""
    out = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        s = line.split("#", 1)[0].strip()
        if not s or s.startswith("-"):
            continue
        m = _NAME.match(s)
        if m:
            out.append((norm(m.group(1)), s))
    return out


def filter_lite(lines: list[tuple[str, str]]) -> list[str]:
    return [orig for n, orig in lines if n not in {norm(x) for x in LITE_EXCLUDE}]


def installed_version(name: str) -> str | None:
    try:
        return metadata.version(name)
    except metadata.PackageNotFoundError:
        return None


def render_lock(names: list[str], version_of=installed_version) -> str:
    """Pinned lock text for the direct dependencies, built from importlib.metadata (never `pip freeze`, so conda `@ file:///` paths cannot leak)."""
    lines = [f"# Generated by scripts/freeze_environment.py; Python {platform.python_version()} on {platform.system()}",
             "# Direct dependencies pinned to the versions installed when the results were produced."]
    missing = []
    for n in sorted(set(names)):
        v = version_of(n)
        (lines.append(f"{n}=={v}") if v else missing.append(n))
    if missing:
        lines.append("# not installed in this environment: " + ", ".join(missing))
    return "\n".join(lines) + "\n"


def license_info(name: str) -> str:
    try:
        md = metadata.metadata(name)
    except metadata.PackageNotFoundError:
        return "not installed"
    lic = (md.get("License-Expression") or md.get("License") or "").strip().splitlines()[0:1]
    cls = [c.split("::")[-1].strip() for c in md.get_all("Classifier", []) if c.startswith("License ::")]
    return (lic[0][:60] if lic and lic[0] else "") or "; ".join(cls) or "unknown (check the package page)"


def venv_python(venv_dir: Path) -> Path:
    return Path(venv_dir) / ("Scripts/python.exe" if sys.platform.startswith("win") else "bin/python")
